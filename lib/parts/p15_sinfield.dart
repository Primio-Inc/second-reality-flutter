/// Part 15 — the 3D sinusfield (`3DSINFLD.EXE`, built from COMAN/: MAIN.C +
/// ASM.ASM + THELOOP.INC). A rolling blue/red wave landscape that rises out of
/// the bottom of the screen, rolls past the camera, and sinks away again.
///
/// It is a voxel raycaster, one ray per screen column, and every number below is
/// the original's:
///
///  - The terrain is SEPARABLE: `height(x,y) = wave1[x] + wave2[y]`, two 32768-
///    entry signed tables (COMAN/W1DTA.BIN, W2DTA.BIN — precomputed, and with a
///    rand() term in their generator, so they must be replayed rather than
///    regenerated), plus `zwave[j]`, a 16-amplitude ripple along the ray that
///    DOLOOP.C bakes into the unrolled loop. The camera sits 240 units above the
///    field (`bx += zwave[j] - 240`).
///  - THELOOP.INC (generated by COMAN/DOLOOP.C) marches each ray 192 steps and,
///    wherever the terrain rises above the ray, paints the column upward until
///    the ray climbs clear. The ray height lives in `eax` as 16.16 fixed point
///    with the INTEGER IN THE LOW WORD — that is what DOLOOP.C's `wflip` is for:
///    it pre-swaps every constant so the fraction lands in the high word and the
///    integer in `ax`, and `adc ax,0` folds the fraction's carry back into the
///    integer. [_sar]-free 32-bit adds and their carries are emulated exactly.
///    The `adc cx,0` on the ray's SLOPE is not optional: without it the slope
///    never flattens toward the horizon, every column paints to the top of the
///    screen and the sky disappears.
///  - The column's colour is the terrain height itself: `(bx + 120 - j/8) & 0xFF`
///    shifted right one, i.e. one of the 128 entries of MAIN.C's blue ramp, with
///    a distance term that darkens the far field.
///  - `vbuf` is 160 bytes per row: one byte covers TWO screen pixels (docopy
///    writes it to the VGA with plane masks 0x3 and 0xC, so each byte lands in
///    two planes = two pixels). The field is therefore 160x200, doubled across.
///  - docopy copies vbuf rows 60..199 to screen rows 70..209 and only THEN
///    clears vbuf rows 68..97 for the next frame — so the clear must happen
///    before a frame is drawn, never between drawing and showing it.
///
/// TIMING — two clocks, as in the original, and both measured off the capture
/// (every gate here reads `dis_musplus()`, which cannot be derived):
///  - THE RETRACE CLOCK drives `startrise`, the vertical offset docopy writes
///    the picture at: it steps once per RETRACE (it lives inside doit()'s
///    `while(frepeat--)` loop), 160 -> 0, which is why the field rises at exactly
///    one row per retrace. Fitting that rise in the capture pins frame 0 to
///    capture 439.43 (predicted vs measured top row: 199/199, 143/143, 96/95,
///    93/93).
///  - THE RENDER CLOCK drives the camera and the rotation, which step once per
///    RENDERED FRAME — and the original did NOT render at 70 Hz. Matching our
///    horizon profile against the capture's at four different times gives our
///    frame 192/362/535/784 for capture 445.12/450/455/462: one frame per TWO
///    retraces, i.e. 35 fps, stable to ±2 frames across 22 seconds (`dis_waitb()`
///    returned 2 every frame on that machine — the effect could not hit 70 Hz).
///    Those fits also show the render loop starting ~15 retraces late (a startup
///    hitch), which is [_stallRetraces].
///  - THE SINK: `if(a > -30 && a < 0) startrise++` runs the rise backwards at the
///    end. Measured at capture 465.87 -> [kSinkAt]. The part then breaks out at
///    `a > -8`, and since dis_musplus counts music ROWS, the 22 rows between -30
///    and -8 are 2.54s at MUSIC1's tempo — the capture's field slides off and
///    the next part appears 2.56s later. The two gates confirm each other.
class SinFieldPart extends Part {
  /// The measured startup hitch before the render loop settles into its
  /// two-retraces-per-frame cadence (see the timing note above).
  static const int _stallRetraces = 15;

  /// One rendered frame per two retraces — the rate the original actually ran at.
  static const int _retracesPerFrame = 2;

  /// `while(dis_musplus() > -30 && ... ) startrise++` — the field sinks away.
  /// Capture 465.87 -> here.
  static const double kSinkAt = 466.07;

  static const int _bail = 192;
  static const int _bailHalve = 64;
  static const int _horizonY = 70;
  static const int _mask32 = 0xFFFFFFFF;

  final IndexedSurface _s = IndexedSurface(320, 200);

  late final Int16List _w1;
  late final Int16List _w2;
  late final Int16List _sin;
  late final Int16List _zwave;

  /// 160 bytes per row x 200 rows, in a 64K buffer as the original halloc's.
  final Uint8List _vbuf = Uint8List(65536);

  int _frame = 0; // rendered frames elapsed
  int _rot = 0;
  int _rot2 = 0;
  int _xwav = 0;
  int _ywav = 0;

  static const int _firstRayDir = -(200 - _horizonY) * 2560;

  @override
  IndexedSurface? get indexed => _s;

  /// DOLOOP.C's `wflip`: swap the halves of a 32-bit word, so the integer of a
  /// 16.16 value ends up in the low word where `ax` can compare it.
  static int _wflip(int v) {
    v &= _mask32;
    return (((v & 0xFFFF) << 16) | (v >>> 16)) & _mask32;
  }

  static int _i16(int v) {
    v &= 0xFFFF;
    return v >= 0x8000 ? v - 0x10000 : v;
  }

  @override
  void init() {
    final t = AssetStore.sinfield!;
    _w1 = t.wave1;
    _w2 = t.wave2;

    _sin = Int16List(1024);
    for (var i = 0; i < 1024; i++) {
      _sin[i] = (256 * math.sin(2 * math.pi * i / 1024)).round();
    }
    // DOLOOP.C: `zwave[i] = 16.0*sin(i*PI*2*3/bail)` — three ripples along the ray.
    _zwave = Int16List(_bail);
    for (var i = 0; i < _bail; i++) {
      _zwave[i] = (16.0 * math.sin(i * math.pi * 2.0 * 3.0 / _bail)).toInt();
    }

    _s.palette = _buildPalette();
    _reset();
  }

  /// MAIN.C's DAC. Only entries 0..127 are ever drawn (the column colour is a
  /// byte shifted right one), but the whole thing is built as the original does.
  VgaPalette _buildPalette() {
    final pal = VgaPalette.black();
    final b = pal.bytes;
    for (var a = 0; a < 256; a++) {
      final uc = (223 - a * 22 ~/ 26) * 3;
      var v = (230 - a) ~/ 4 + _sin[(a * 4) & 1023] ~/ 32;
      v = v.clamp(0, 63);
      b[uc + 1] = v;
      b[uc + 2] = math.min(63, (255 - a) ~/ 3);
      var r = (a - 220).abs();
      if (r > 40) r = 40;
      b[uc] = (40 - r) ~/ 3;
    }
    for (var a = 0; a < 768 - 16 * 3; a++) {
      b[a] = math.min(63, b[a] * 9 ~/ 6);
    }
    for (var a = 0; a < 24; a++) {
      final uc = (255 - a) * 3;
      b[uc] = math.max(0, a - 4) ~/ 2;
      b[uc + 1] = 0;
      b[uc + 2] = 0;
    }
    b[0] = b[1] = b[2] = 0;
    return pal;
  }

  void _reset() {
    _frame = 0;
    _rot = 0;
    _rot2 = 0;
    _xwav = 0;
    _ywav = 0;
    _vbuf.fillRange(0, _vbuf.length, 0);
  }

  /// theloop: march one ray and paint the terrain column it hits.
  void _docol(int xw, int yw, int xa, int ya, int bp) {
    var si = xw & 0xFFFE;
    var di = yw & 0xFFFE;
    final xs1 = xa & 0xFFFE;
    final ys1 = ya & 0xFFFE;
    final xs2 = (xs1 * 2) & 0xFFFF;
    final ys2 = (ys1 * 2) & 0xFFFF;

    var e = 0; // eax: ray height, integer in the low word
    var c = _wflip(_firstRayDir); // ecx: the ray's slope, per screen row
    final step2560 = _wflip(2560);

    var j = 0;
    while (j < _bail) {
      final wide = j >= _bailHalve;
      si = (si + (wide ? xs2 : xs1)) & 0xFFFF;
      var bx = _w1[si >> 1];
      di = (di + (wide ? ys2 : ys1)) & 0xFFFF;
      bx = _i16(bx + _w2[di >> 1]);
      bx = _i16(bx + _zwave[j] - 240);

      if (_i16(e & 0xFFFF) < bx) {
        final col = ((bx + 120 - j ~/ 8) & 0xFF) >> 1;
        final step = _wflip(j * 2560);
        while (true) {
          var s = (e & _mask32) + step;
          var carry = s > _mask32 ? 1 : 0;
          e = s & _mask32;
          final ax = ((e & 0xFFFF) + carry) & 0xFFFF;
          e = (e & 0xFFFF0000) | ax;

          if (bp >= 0 && bp < 65536) _vbuf[bp] = col;
          bp -= 160;

          // `add ecx,<2560>` / `adc cx,0` — the slope flattens by one row.
          s = (c & _mask32) + step2560;
          carry = s > _mask32 ? 1 : 0;
          c = s & _mask32;
          c = (c & 0xFFFF0000) | (((c & 0xFFFF) + carry) & 0xFFFF);

          if (_i16(ax) >= bx || bp < -160) break;
        }
      }

      // seeko: advance the ray along its slope (twice past the halfway point).
      var s = (e & _mask32) + (c & _mask32);
      var carry = s > _mask32 ? 1 : 0;
      e = s & _mask32;
      if (wide) {
        s = (e & _mask32) + (c & _mask32) + carry;
        carry = s > _mask32 ? 1 : 0;
        e = s & _mask32;
      }
      e = (e & 0xFFFF0000) | (((e & 0xFFFF) + 0xFFFF + carry) & 0xFFFF);

      j += wide ? 2 : 1;
    }
  }

  /// One rendered frame of doit().
  void _step() {
    // docopy clears these rows AFTER showing the frame, so they are cleared here
    // BEFORE this frame is drawn — never between drawing and showing.
    _vbuf.fillRange(68 * 160, 98 * 160, 0);

    _rot2 += 4;
    _rot += (_sin[_rot2 & 1023] / 15).truncate();
    final r = (_rot / 8).floor();
    final rsin = _sin[r & 1023];
    final rcos = _sin[(r + 256) & 1023];
    final rsin2 = _sin[(r + 177) & 1023];
    final rcos2 = _sin[(r + 177 + 256) & 1023];

    final xw = _xwav, yw = _ywav;
    for (var a = 0; a < 160; a++) {
      final x = a - 80;
      const y = 160;
      final xa = ((x * rcos + y * rsin) / 256).truncate();
      final ya = ((y * rcos2 - x * rsin2) / 256).truncate();
      final b = (a & 1) * 80 + (a >> 1) + 199 * 160;
      _docol(_i16(xw), _i16(yw), _i16(xa), _i16(ya), b);
      if (a == 80) {
        _xwav = _i16(_xwav + xa * 4);
        _ywav = _i16(_ywav + ya * 4);
      }
    }
    _frame++;
  }

  /// docopy: vbuf rows 60..199 -> screen rows 70..209, offset down by
  /// [startrise]. Everything above is black (the original clears rows 52..69 of
  /// the page and never touches the rest).
  void _blit(int startrise) {
    final px = _s.pixels;
    px.fillRange(0, px.length, 0);
    for (var sy = 0; sy < 200; sy++) {
      final vr = 60 + (sy - 70 - startrise);
      if (vr < 60 || vr > 199) continue;
      final src = vr * 160;
      final dst = sy * 320;
      for (var a = 0; a < 160; a++) {
        final v = _vbuf[src + (a & 1) * 80 + (a >> 1)];
        px[dst + a * 2] = v;
        px[dst + a * 2 + 1] = v;
      }
    }
  }

  @override
  void update(double t, List<int> syncCodes) {
    final retrace = (t * kDemoFps).floor();

    // The rise (one row per retrace, 160 -> 0), then the sink at the music gate.
    var startrise = math.max(0, 160 - retrace);
    final sinkRetraces =
        ((musicTime - kSinkAt) * kDemoFps).floor();
    if (sinkRetraces > 0) startrise = math.min(160, sinkRetraces);

    final target =
        math.max(0, (retrace - _stallRetraces) ~/ _retracesPerFrame);
    if (target < _frame) _reset();
    var budget = 300; // bounded catch-up, so a seek cannot hang a frame
    while (_frame < target && budget-- > 0) {
      _step();
    }
    if (_frame < target) _frame = target;

    _blit(startrise);
  }
}
