import 'dart:math' as math;
import 'dart:typed_data';

import '../engine/asset_store.dart';
import '../engine/indexed_surface.dart';
import '../engine/part.dart';

/// Part 16 — the jellypic (`JPLOGO.EXE`, built from JPLOGO/JP.C + ASM.ASM +
/// the generated ZOOM.INC). The "Ice Kingdom" picture scrolls in from the top,
/// then wobbles like jelly: it squashes and stretches vertically on a spring,
/// and each scanline's WIDTH rides a sine down the picture, so the sides bulge
/// as it compresses.
///
/// Everything here is the original's:
///
///  - THE PICTURE is a 320x400 field, but JP.C only draws columns 70..253 of it
///    (`memcpy(row[y], rowbuf+70, 184)`), plus a 185th byte of colour 65 that
///    the zoom's last sample can land on. The black bars in the file are never
///    drawn — the 184-wide art is centred in the 320-wide screen, which is where
///    the pillarbox on screen comes from.
///  - THE SPRING is precomputed, not simulated per frame. main() runs 200
///    keyframes of `y2a += 16; if (y2 > 400*16) { y2 -= y2a; y2a = -y2a*mika/8; }`
///    — a bouncing bottom edge, a top edge chasing it, and a coupling term that
///    pulls the two toward a 400-row height — then INTERPOLATES them 4x into
///    framey1t/framey2t. doit() just reads that table with the RETRACE counter,
///    so the jelly's shape is a pure function of the retrace and cannot drift
///    with our frame rate.
///  - THE ZOOM is 54 unrolled routines (ZOOM.INC), one per even width from 140
///    to 244, generated by JPLOGO/DOL.C — and DOL.C gives the mapping exactly:
///    for width w, `le = 160 - w/2`, `c = w + 1`, and a screen pixel x inside
///    [le, le+w] samples source `((x - le)*185 + c/2) / c`; outside it is index
///    0 (black). Widths outside 140..244 clamp to the nearest routine, and width
///    0 just clears the row. That table is precomputed here in [_zoom].
///  - THE WOBBLE, per drawn row: source row `b = (y-y1)*400/(y2-y1)`, width
///    `a = 184 + (sin1024[b*32/25]*xsc + 32)/64` masked even, with amplitude
///    `xsc = (400 - (y2-y1))/8` — zero at full height, so the picture only
///    bulges while it is squashed.
///
/// TIMING. The part is not on a cue; both of its phases are capture-measured,
/// and they check out against the code's own retrace counts:
///  - THE SCROLL-IN starts at capture 468.42 -> 468.62 here. It is pure CRTC:
///    `y` walks 400*64 -> 0 with `a = 64, a += 6` per retrace and `scrolly(y/64)`
///    sets the display start row, so the picture slides DOWN into the frame,
///    bottom edge first. That ramp takes 83 retraces; the capture's picture
///    grows from nothing to full height in 1.17s = 82 retraces, and its
///    accelerating height profile matches `(3k^2 + 61k)/64` row for row.
///  - THE JELLY (doit) waits for `dis_musplus() >= 4`, but that gate has already
///    passed by the time the scroll ends: the capture's first squash is at
///    469.63, exactly the retrace the scroll finishes. So there is no separate
///    constant — doit starts when the scroll-in ends, as the code does.
class JpLogoPart extends Part {
  /// The scroll-in: `a = 64; while (y > 0) { y -= a; a += 6; }` over y = 400*64.
  static final int _scrollRetraces = _scrollOffsets.length;

  /// `while (!dis_exit() && frame < 700)`.
  static const int _lastFrame = 700;

  final IndexedSurface _s = IndexedSurface(320, 400);

  /// The picture's drawn columns: 400 rows x 185 bytes (cols 70..253, then the
  /// colour-65 byte JP.C appends).
  late final Uint8List _rows;

  /// Per even width 140..244: the 320 source indices a screen row samples, or
  /// -1 for the black margin. (DOL.C's `xt[]`.)
  late final List<Int16List> _zoom;

  /// framey1t / framey2t — the interpolated spring, one entry per retrace.
  late final Int32List _y1t;
  late final Int32List _y2t;

  late final Int16List _sin;

  @override
  IndexedSurface? get indexed => _s;

  /// The CRTC start row for each retrace of the scroll-in.
  static final List<int> _scrollOffsets = _buildScroll();

  static List<int> _buildScroll() {
    final out = <int>[];
    var y = 400 * 64;
    var a = 64;
    while (y > 0) {
      y -= a;
      a += 6;
      if (y < 0) y = 0;
      out.add(y ~/ 64);
    }
    return out;
  }

  @override
  void init() {
    final pic = AssetStore.images['icekngdm']!;
    final src = pic.pixels; // 320x400

    // The DAC, with JP.C's two black entries: index 64 is forced black (and the
    // picture's own colour 0 is remapped onto it), and index 0 is what the zoom
    // writes outside the picture.
    final pal = pic.palette;
    pal.setRgb(64, 0, 0, 0);
    _s.palette = pal;

    _rows = Uint8List(400 * 185);
    for (var y = 0; y < 400; y++) {
      for (var x = 0; x < 184; x++) {
        var v = src[y * 320 + 70 + x];
        if (v == 0) v = 64; // `if (row[a][b] == 0) row[a][b] = 64;`
        _rows[y * 185 + x] = v;
      }
      _rows[y * 185 + 184] = 65;
    }

    _sin = Int16List(1024);
    for (var i = 0; i < 1024; i++) {
      _sin[i] = (256 * math.sin(2 * math.pi * i / 1024)).round();
    }

    // ZOOM.INC, from DOL.C's generator.
    _zoom = List.generate(53, (k) {
      final w = 140 + k * 2;
      final le = 160 - w ~/ 2;
      final ri = 160 + w ~/ 2;
      final c = ri - le + 1;
      final map = Int16List(320);
      for (var x = 0; x < 320; x++) {
        map[x] = (x < le || x > ri) ? -1 : ((x - le) * 185 + c ~/ 2) ~/ c;
      }
      return map;
    });

    _buildSpring();
  }

  /// main()'s 200-keyframe spring, then the 4x interpolation into the per-retrace
  /// tables. Ported line for line — it is the whole animation.
  void _buildSpring() {
    final y1k = Int32List(201);
    final y2k = Int32List(201);
    var halt = 0;
    var y1 = 0, y1a = 500;
    var y2 = 399 * 16, y2a = 500;
    var mika = 1;
    var a = 0;

    for (var frame = 0; frame < 200; frame++) {
      if (halt == 0) {
        y1 += y1a;
        y2 += y2a;

        y2a += 16;
        if (y2 > 400 * 16) {
          y2 -= y2a;
          y2a = -y2a * mika ~/ 8;
          if (mika < 4) mika += 3;
        }
        y1a += 16;

        final la = a;
        a = (y2 - y1) - 400 * 16;
        // The original tests the SIGN BIT of a 16-bit int, so the coupling only
        // damps y1 when the height crosses 400 rows.
        if (((a & 0x8000) ^ (la & 0x8000)) != 0) {
          y1a = y1a * 7 ~/ 8;
        }
        y1a += a ~/ 8;
        y2a -= a ~/ 8;
      }

      if (frame > 90) {
        if (y2 >= 399 * 16) {
          y2 = 400 * 16;
          halt = 1;
        } else {
          y2a = 8;
        }
        y1 = y2 - 400 * 16;
      }

      y1k[frame] = y1;
      y2k[frame] = y2;
    }
    y1k[200] = y1k[199];
    y2k[200] = y2k[199];

    _y1t = Int32List(800);
    _y2t = Int32List(800);
    for (var i = 0; i < 800; i++) {
      final b = i ~/ 4;
      final c = i & 3;
      final d = 3 - c;
      _y1t[i] = (y1k[b] * d + y1k[b + 1] * c) ~/ 3;
      _y2t[i] = (y2k[b] * d + y2k[b + 1] * c) ~/ 3;
    }
  }

  /// linezoom: one screen row, scaled to [width] and clamped as ZOOM.INC's jump
  /// table clamps it. [srcRow] < 0 clears the row.
  void _lineZoom(int y, int srcRow, int width) {
    final px = _s.pixels;
    final dst = y * 320;
    if (srcRow < 0 || width <= 0) {
      px.fillRange(dst, dst + 320, 0);
      return;
    }
    var w = width;
    if (w > 318) w = 318;
    w &= ~1;
    if (w < 140) w = 140;
    if (w > 244) w = 244;
    final map = _zoom[(w - 140) >> 1];
    final base = srcRow * 185;
    for (var x = 0; x < 320; x++) {
      final s = map[x];
      px[dst + x] = s < 0 ? 0 : _rows[base + s];
    }
  }

  /// doit(): one retrace of the jelly.
  void _drawJelly(int frame) {
    final f = math.min(frame, 511);
    final y1 = _y1t[f] ~/ 16;
    final y2 = _y2t[f] ~/ 16;
    final h = y2 - y1;
    if (h <= 0) {
      for (var y = 0; y < 400; y++) {
        _lineZoom(y, -1, 0);
      }
      return;
    }
    final xsc = (400 - h) ~/ 8;
    for (var y = 0; y < 400; y++) {
      if (y < y1 || y >= y2) {
        _lineZoom(y, -1, 0);
      } else {
        final b = (y - y1) * 400 ~/ h;
        var a = 184 + (_sin[(b * 32 ~/ 25) & 1023] * xsc + 32) ~/ 64;
        a &= ~1;
        _lineZoom(y, b, a);
      }
    }
  }

  /// The scroll-in: the picture drawn once at full width, shown through the CRTC
  /// start address, so screen row s shows picture row `offset + s`.
  void _drawScroll(int offset) {
    for (var y = 0; y < 400; y++) {
      final src = offset + y;
      _lineZoom(y, src < 400 ? src : -1, 184);
    }
  }

  @override
  void update(double t, List<int> syncCodes) {
    final retrace = (t * kDemoFps).floor();
    if (retrace < _scrollRetraces) {
      _drawScroll(_scrollOffsets[math.max(0, retrace)]);
      return;
    }
    final frame = math.min(retrace - _scrollRetraces, _lastFrame);
    _drawJelly(frame);
  }
}
