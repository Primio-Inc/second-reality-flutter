#!/usr/bin/env python3
"""PLZPART tables -> assets/tables/plasma.srt

The plasma's three sine tables ship as TASM include files (PSINI.INC,
LSINI4.INC, LSINI16.INC), generated by the `#ifdef DO_TABLES` block in
PLZPART/PLZ.C.  We parse the shipped .INC files -- they are the bytes the demo
actually ran -- and verify each one against the generator formula, so a
mismatch in either direction is caught.

PTAU (the 65-entry cosine ramp the palettes are built from) ships as PTAU.PRE,
a C initialiser.

The cube (vect()) needs three more shipped tables, which are TASM includes too:
SINIT.INC (the 15-bit sine, with kosinit = sinit + 256 entries), SPLINE.INC (the
cubic spline's four 256-entry basis rows) and RATA.INC (the camera/object path's
control points, 8 channels each: tx, ty, dis, kx, ky, kz, ls_kx, ls_ky).

Layout of plasma.srt:
    "SRP2"
    u8   version (2)
    psini   : 16384 bytes            (unsigned, 0..128)
    lsini4  :  8192 x u16le
    lsini16 :  8192 x u16le
    ptau    :   129 bytes
    sinit   :  1280 x i16le          (kosinit[a] == sinit[a + 256])
    spline  :  1024 x i16le          (4 x 256 basis weights, 1.0 = 32768)
    u16le   points, then points x 8 x i16le  (RATA.INC)
"""

import math
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "original" / "PLZPART"
OUT = ROOT / "assets" / "tables" / "plasma.srt"

DPII = 3.1415926535 * 2.0


def parse_asm_table(path, directive):
    """Parse a TASM `db`/`dw` include file into a list of ints."""
    vals = []
    for line in path.read_text(errors="replace").splitlines():
        line = line.strip()
        if not line.lower().startswith(directive):
            continue
        for tok in re.split(r"[,\s]+", line[len(directive):].strip()):
            if tok:
                vals.append(int(tok))
    return vals


def parse_asm_bytes(path):
    """SINIT.INC is a flat `db` byte stream (the line breaks fall mid-word)."""
    vals = []
    for line in path.read_text(errors="replace").splitlines():
        line = line.strip()
        if not line.lower().startswith("db"):
            continue
        for tok in re.split(r"[,\s]+", line[2:].strip()):
            if tok:
                vals.append(int(tok))
    return vals


def parse_rata(path):
    """RATA.INC: `dw` rows of 8 channels, with a `kkk` equate and a REPT tail."""
    env = {}
    pts = []
    rept = None
    for line in path.read_text(errors="replace").splitlines():
        line = line.split(";")[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"(\w+)\s*=\s*(\d+)", line)
        if m:
            env[m.group(1)] = int(m.group(2))
            continue
        m = re.fullmatch(r"REPT\s+(\d+)", line, re.I)
        if m:
            rept = (int(m.group(1)), [])
            continue
        if re.fullmatch(r"ENDM", line, re.I):
            n, rows = rept
            pts.extend(rows * n)
            rept = None
            continue
        if not line.lower().startswith("dw"):
            continue
        row = []
        for tok in re.split(r"[,\s]+", line[2:].strip()):
            if not tok:
                continue
            m = re.fullmatch(r"(\w+)\*(\w+)", tok)
            if m:
                row.append(int(env.get(m.group(1), m.group(1)))
                           * int(env.get(m.group(2), m.group(2))))
            else:
                row.append(int(env.get(tok, tok)))
        assert len(row) == 8, row
        if rept is not None:
            rept[1].append(row)
        else:
            pts.append(row)
    return pts


def parse_ptau(path):
    text = path.read_text(errors="replace")
    text = text[text.index("{") + 1: text.rindex("}")]
    return [int(t) for t in re.split(r"[,\s]+", text.strip()) if t]


def trunc(x):
    """C double->int conversion: truncate toward zero."""
    return int(x)


def gen_psini(a):
    return trunc(
        math.sin(a * DPII / 4096) * 55
        + math.sin(a * DPII / 4096 * 6) * 5
        + math.sin(a * DPII / 4096 * 21) * 4
        + 64
    )


def gen_lsini4(a):
    return trunc(
        (
            math.sin(a * DPII / 4096) * 55
            + math.sin(a * DPII / 4096 * 5) * 8
            + math.sin(a * DPII / 4096 * 15) * 2
            + 64
        )
        * 8
    )


def gen_lsini16(a):
    return trunc(
        (
            math.sin(a * DPII / 4096) * 55
            + math.sin(a * DPII / 4096 * 4) * 5
            + math.sin(a * DPII / 4096 * 17) * 3
            + 64
        )
        * 16
    )


def gen_ptau(a):
    if a == 0:
        return 0
    return trunc(math.cos(a * DPII / 128 + 3.1415926535) * 31 + 32)


# The only entries where the shipped tables disagree with the generator, both
# at a = 3072/7168, i.e. exactly 3*pi/2 where lsini4's expression lands on the
# integer 3.0.  Borland evaluated it in the x87's 80-bit registers, got
# 2.9999..., and truncated to 23; an IEEE double gives exactly 24.  The shipped
# table is what the demo ran, so it wins -- this just pins the deviation down.
KNOWN_TRUNC = {("lsini4", 3072): (23, 24), ("lsini4", 7168): (23, 24)}


def verify(name, shipped, gen, count):
    bad = []
    for a in range(count):
        want = gen(a)
        if shipped[a] == want:
            continue
        known = KNOWN_TRUNC.get((name, a))
        if known == (shipped[a], want):
            continue
        bad.append(a)
    if bad:
        print(f"  {name}: {len(bad)}/{count} MISMATCH, first at {bad[:5]}")
        for a in bad[:5]:
            print(f"    [{a}] shipped={shipped[a]} formula={gen(a)}")
        return False
    known_here = [a for (n, a) in KNOWN_TRUNC if n == name]
    note = (f" ({len(known_here)} known x87-truncation deviations at "
            f"{sorted(known_here)})" if known_here else "")
    print(f"  {name}: {count} entries, byte-exact vs formula{note}")
    return True


def main():
    psini = parse_asm_table(SRC / "PSINI.INC", "db")
    lsini4 = parse_asm_table(SRC / "LSINI4.INC", "dw")
    lsini16 = parse_asm_table(SRC / "LSINI16.INC", "dw")
    ptau = parse_ptau(SRC / "PTAU.PRE")

    print(f"parsed: psini={len(psini)} lsini4={len(lsini4)} "
          f"lsini16={len(lsini16)} ptau={len(ptau)}")
    assert len(psini) == 16384, len(psini)
    assert len(lsini4) == 8192, len(lsini4)
    assert len(lsini16) == 8192, len(lsini16)
    assert len(ptau) == 129, len(ptau)

    print("verifying against PLZ.C's DO_TABLES generator:")
    ok = all([
        verify("psini", psini, gen_psini, 16384),
        verify("lsini4", lsini4, gen_lsini4, 8192),
        verify("lsini16", lsini16, gen_lsini16, 8192),
        verify("ptau", ptau, gen_ptau, 129),
    ])
    if not ok:
        sys.exit("table verification FAILED")

    print(f"ranges: psini {min(psini)}..{max(psini)}  "
          f"lsini4 {min(lsini4)}..{max(lsini4)}  "
          f"lsini16 {min(lsini16)}..{max(lsini16)}")

    # --- the cube's tables ---------------------------------------------------
    sb = parse_asm_bytes(SRC / "SINIT.INC")
    sinit = [struct.unpack("<h", bytes(sb[i * 2:i * 2 + 2]))[0]
             for i in range(1280)]
    spline = parse_asm_table(SRC / "SPLINE.INC", "dw")
    rata = parse_rata(SRC / "RATA.INC")
    assert len(spline) == 1024, len(spline)
    print(f"sinit: 1280 entries (kosinit = +256), spline: {len(spline)}, "
          f"rata: {len(rata)} control points")

    # SINIT.INC's own generator is not in the tree; the shipped table is
    # trunc(sin(a * 2pi / 1024) * 32766) to within a unit everywhere, and it IS
    # what the demo ran, so it ships verbatim.  This only pins the deviation.
    worst = max(abs(sinit[a] - math.sin(a * DPII / 1024) * 32766)
                for a in range(1024))
    print(f"  sinit vs trunc(sin * 32766): worst deviation {worst:.2f}")
    assert worst < 2.0, worst
    # kosinit is literally the same table read 256 entries in (a quarter turn).
    for a in range(1024):
        assert sinit[(a + 256) % 1024] == sinit[a + 256] or a + 256 >= 1024

    buf = bytearray(b"SRP2")
    buf.append(2)
    buf += bytes(v & 0xFF for v in psini)
    buf += struct.pack("<8192h", *lsini4)
    buf += struct.pack("<8192h", *lsini16)
    buf += bytes(ptau)
    buf += struct.pack("<1280h", *sinit)
    buf += struct.pack("<1024h", *spline)
    buf += struct.pack("<H", len(rata))
    for p in rata:
        buf += struct.pack("<8h", *p)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(buf)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(buf)} bytes)")


if __name__ == "__main__":
    main()
