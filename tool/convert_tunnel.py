#!/usr/bin/env python3
"""Bundle the dot-tunnel lookup tables (TUNNELI part) as assets/tables/tunnel.srt.

Provenance (public domain, Unlicense — github.com/mtuomi/SecondReality):
  TUNNELI/TUNNEL.DAT -> pcalc[138][64] {int16 x, int16 y}
      Precalculated tunnel rings: for each radius index r (0..137) the 64 dot
      positions of that ring, already centred on the 320x200 screen. Generated
      by TUNNELI/BALLGEN2.PAS:
          z = r + 10
          x = 160 + round(sin(a*pi/32) * round(z*1.7))   { 1.7 = wide ellipse }
          y = 100 + round(cos(a*pi/32) * z)
  TUNNELI/SINIT.DAT  -> sinit[4097] + cosit[2049] (int16)
      The tunnel's snaking path tables, amplitude growing with the index.
      Generated by TUNNELI/SINGEN.PAS:
          sinit[x] = round(sin(x/128*pi) * ((x*3) div 128))
          cosit[x] = round(cos(x/128*pi) * ((x*4) div 64))

Both .DAT files are verified against those generator formulas here, so the
bundled bytes are provably the original tables. (Note: the generator formulas
COMMENTED OUT inside TUNNELI/TUN10.PAS are stale and do NOT match the data —
the .DAT files are the ground truth.)

Output format, assets/tables/tunnel.srt:
  'SRT1' | u16 radii(138) | u16 pts(64) | radii*pts * {i16 x, i16 y}
        | u16 sinLen(4097) | u16 cosLen(2049) | i16 sin[] | i16 cos[]

Usage: python3 tool/convert_tunnel.py
"""
import math
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLONE = ROOT / "original"  # the vendored original source (see original/VENDORED.md)

RADII, PTS = 138, 64
SIN_LEN, COS_LEN = 4097, 2049


def prnd(x):
    """Turbo Pascal Round: nearest, ties to even (round(42.5) = 42)."""
    return int(round(x))


def main():
    tun = (CLONE / "TUNNELI/TUNNEL.DAT").read_bytes()
    sin = (CLONE / "TUNNELI/SINIT.DAT").read_bytes()
    assert len(tun) == RADII * PTS * 4, f"TUNNEL.DAT size {len(tun)}"
    assert len(sin) == (SIN_LEN + COS_LEN) * 2, f"SINIT.DAT size {len(sin)}"

    pcalc = struct.unpack(f"<{RADII * PTS * 2}h", tun)
    sc = struct.unpack(f"<{SIN_LEN + COS_LEN}h", sin)
    sinit, cosit = sc[:SIN_LEN], sc[SIN_LEN:]

    # Verify against the original generators (BALLGEN2.PAS / SINGEN.PAS).
    bad = 0
    for r in range(RADII):
        z = r + 10
        for a in range(PTS):
            x = 160 + prnd(math.sin(a * math.pi / 32) * prnd(z * 1.7))
            y = 100 + prnd(math.cos(a * math.pi / 32) * z)
            if (pcalc[(r * PTS + a) * 2], pcalc[(r * PTS + a) * 2 + 1]) != (x, y):
                bad += 1
    sbad = sum(1 for x in range(SIN_LEN)
               if sinit[x] != prnd(math.sin(x / 128 * math.pi) * ((x * 3) // 128)))
    cbad = sum(1 for x in range(COS_LEN)
               if cosit[x] != prnd(math.cos(x / 128 * math.pi) * ((x * 4) // 64)))
    print(f"verify: pcalc {bad} mismatches, sinit {sbad}, cosit {cbad}")
    if bad or sbad or cbad:
        sys.exit("tables do not match the original generators — aborting")

    out = bytearray(b"SRT1")
    out += struct.pack("<HH", RADII, PTS)
    out += tun
    out += struct.pack("<HH", SIN_LEN, COS_LEN)
    out += sin

    dst = ROOT / "assets/tables/tunnel.srt"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(out)
    print(f"wrote {dst} ({len(out)} bytes)")


if __name__ == "__main__":
    main()
